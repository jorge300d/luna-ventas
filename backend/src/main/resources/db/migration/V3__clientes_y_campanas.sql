-- Clientes que compran por la web o escriben por WhatsApp
CREATE TABLE clientes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(80),
    telefono        VARCHAR(20)  NOT NULL UNIQUE,   -- formato 51XXXXXXXXX
    distrito        VARCHAR(80),
    origen          VARCHAR(20)  NOT NULL CHECK (origen IN ('web_pedido','web_contacto','whatsapp','manual')),
    acepta_ofertas  BOOLEAN      NOT NULL DEFAULT FALSE,
    acepta_en       TIMESTAMP WITH TIME ZONE,
    baja_en         TIMESTAMP WITH TIME ZONE,
    intereses       VARCHAR(120) NOT NULL DEFAULT '',  -- categorías compradas, separadas por coma
    total_pedidos   INTEGER      NOT NULL DEFAULT 0,
    total_gastado   NUMERIC(10,2) NOT NULL DEFAULT 0,
    ultimo_contacto TIMESTAMP WITH TIME ZONE,
    creado_en       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_clientes_acepta ON clientes (acepta_ofertas);

ALTER TABLE pedidos ADD COLUMN cliente_id BIGINT REFERENCES clientes (id);
ALTER TABLE contactos ADD COLUMN cliente_id BIGINT REFERENCES clientes (id);

-- Ofertas que se mandan a los clientes
CREATE TABLE campanas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(120) NOT NULL,
    mensaje        VARCHAR(900) NOT NULL,
    categoria      VARCHAR(20),               -- null = todos los que aceptaron
    estado         VARCHAR(12)  NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador','programada','enviando','enviada')),
    automatica     BOOLEAN      NOT NULL DEFAULT FALSE,
    programada_en  TIMESTAMP WITH TIME ZONE,
    enviada_en     TIMESTAMP WITH TIME ZONE,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE envios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campana_id      BIGINT      NOT NULL REFERENCES campanas (id) ON DELETE CASCADE,
    cliente_id      BIGINT      NOT NULL REFERENCES clientes (id),
    estado          VARCHAR(12) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','manual','enviado','entregado','leido','fallido')),
    wa_message_id   VARCHAR(120),
    error           VARCHAR(300),
    actualizado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (campana_id, cliente_id)
);
CREATE INDEX idx_envios_wamid ON envios (wa_message_id);
