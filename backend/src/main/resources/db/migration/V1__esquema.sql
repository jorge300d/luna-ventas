-- Esquema de Luna Ventas
CREATE TABLE productos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120)  NOT NULL,
    descripcion   VARCHAR(400),
    categoria     VARCHAR(20)   NOT NULL CHECK (categoria IN ('blusas','vestidos','pantalones','conjuntos','casacas')),
    precio        NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    precio_antes  NUMERIC(10,2),
    tallas        VARCHAR(120)  NOT NULL DEFAULT '',
    color         VARCHAR(7)    NOT NULL DEFAULT '#E8738F',
    imagen_url    VARCHAR(500),
    nuevo         BOOLEAN       NOT NULL DEFAULT FALSE,
    stock         INTEGER       NOT NULL DEFAULT 0 CHECK (stock >= 0),
    activo        BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_productos_categoria ON productos (categoria) ;

CREATE TABLE pedidos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente    VARCHAR(80)   NOT NULL,
    telefono   VARCHAR(20),
    distrito   VARCHAR(80),
    entrega    VARCHAR(10)   NOT NULL CHECK (entrega IN ('tienda','delivery')),
    estado     VARCHAR(12)   NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','confirmado','entregado','cancelado')),
    total      NUMERIC(10,2) NOT NULL DEFAULT 0,
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pedido_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT        NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
    producto_id      BIGINT        REFERENCES productos (id),
    nombre           VARCHAR(120)  NOT NULL,
    talla            VARCHAR(10)   NOT NULL,
    cantidad         INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(10,2) NOT NULL
);
CREATE INDEX idx_items_pedido ON pedido_items (pedido_id);

CREATE TABLE contactos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(80)   NOT NULL,
    telefono   VARCHAR(20),
    mensaje    VARCHAR(1000) NOT NULL,
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
