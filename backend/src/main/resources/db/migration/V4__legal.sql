-- Prueba de cada consentimiento (Ley 29733): quién, qué aceptó, qué versión del texto y cuándo
CREATE TABLE consentimientos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT       REFERENCES clientes (id),
    tipo        VARCHAR(20)  NOT NULL CHECK (tipo IN ('privacidad','publicidad')),
    otorgado    BOOLEAN      NOT NULL,
    version     VARCHAR(20)  NOT NULL,
    origen      VARCHAR(30)  NOT NULL,
    texto       VARCHAR(500) NOT NULL,
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_consentimientos_cliente ON consentimientos (cliente_id);

ALTER TABLE clientes ADD COLUMN acepta_politica_en TIMESTAMP WITH TIME ZONE;
ALTER TABLE clientes ADD COLUMN eliminado BOOLEAN NOT NULL DEFAULT FALSE;

-- Libro de Reclamaciones virtual (DS 011-2011-PCM y modificatorias)
CREATE TABLE reclamos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             VARCHAR(20)   NOT NULL UNIQUE,
    tipo               VARCHAR(10)   NOT NULL CHECK (tipo IN ('reclamo','queja')),
    nombre             VARCHAR(120)  NOT NULL,
    tipo_documento     VARCHAR(10)   NOT NULL,
    numero_documento   VARCHAR(20)   NOT NULL,
    domicilio          VARCHAR(200)  NOT NULL,
    telefono           VARCHAR(20),
    correo             VARCHAR(120)  NOT NULL,
    menor_de_edad      BOOLEAN       NOT NULL DEFAULT FALSE,
    apoderado          VARCHAR(120),
    bien_tipo          VARCHAR(10)   NOT NULL CHECK (bien_tipo IN ('producto','servicio')),
    monto              NUMERIC(10,2),
    descripcion_bien   VARCHAR(300)  NOT NULL,
    detalle            VARCHAR(2000) NOT NULL,
    pedido             VARCHAR(1000) NOT NULL,
    estado             VARCHAR(12)   NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','respondido')),
    respuesta          VARCHAR(2000),
    respondido_en      TIMESTAMP WITH TIME ZONE,
    correo_enviado     BOOLEAN       NOT NULL DEFAULT FALSE,
    creado_en          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Solicitudes de derechos ARCO y portabilidad
CREATE TABLE solicitudes_datos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(15)   NOT NULL CHECK (tipo IN ('acceso','rectificacion','cancelacion','oposicion','portabilidad','revocacion')),
    nombre          VARCHAR(120)  NOT NULL,
    numero_documento VARCHAR(20)  NOT NULL,
    telefono        VARCHAR(20),
    correo          VARCHAR(120),
    detalle         VARCHAR(1000) NOT NULL,
    estado          VARCHAR(12)   NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','atendida')),
    nota            VARCHAR(1000),
    atendida_en     TIMESTAMP WITH TIME ZONE,
    creado_en       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

